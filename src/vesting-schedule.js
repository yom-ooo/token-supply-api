const CATEGORIES = Object.keys(SCHEDULE);

/**
 * Calculate the number of days between two dates (UTC, ignoring time).
 */
function daysBetween(a, b) {
    const msPerDay = 86400000;
    const utcA = Date.UTC(a.getUTCFullYear(), a.getUTCMonth(), a.getUTCDate());
    const utcB = Date.UTC(b.getUTCFullYear(), b.getUTCMonth(), b.getUTCDate());
    return (utcB - utcA) / msPerDay;
}

/**
 * Get the date corresponding to a given vesting month number.
 * Month N = TGE_DATE + N calendar months.
 */
function getMonthDate(monthIndex) {
    const d = new Date(TGE_DATE);
    d.setUTCMonth(d.getUTCMonth() + monthIndex);
    return d;
}

/**
 * Linearly interpolate between two values.
 */
function lerp(a, b, t) {
    return a + (b - a) * t;
}

/**
 * Calculate circulating supply for a specific category at a given date.
 * Linearly interpolates between monthly data points for daily granularity.
 */
function getCategorySupply(category, date) {
    const schedule = SCHEDULE[category];
    if (!schedule) return 0;

    // Before TGE
    if (date < TGE_DATE) return 0;

    // Find which month interval we're in
    for (let m = 0; m < schedule.length - 1; m++) {
        const monthStart = getMonthDate(m);
        const monthEnd = getMonthDate(m + 1);

        if (date >= monthStart && date < monthEnd) {
            const totalDays = daysBetween(monthStart, monthEnd);
            const elapsedDays = daysBetween(monthStart, date);
            const fraction = totalDays > 0 ? elapsedDays / totalDays : 0;
            return lerp(schedule[m], schedule[m + 1], fraction);
        }
    }

    // Beyond month 60 — fully vested
    return schedule[schedule.length - 1];
}

/**
 * Calculate the total circulating supply at a given date.
 * Returns an object with per-category breakdown and total.
 */
function getCirculatingSupply(date = new Date()) {
    const breakdown = {};
    let total = 0;

    for (const category of CATEGORIES) {
        const amount = getCategorySupply(category, date);
        breakdown[category] = Math.floor(amount);
        total += amount;
    }

    return {
        circulatingSupply: Math.floor(total),
        totalSupply: TOTAL_SUPPLY,
        breakdown,
        date: date.toISOString().split('T')[0],
        tgeDate: TGE_DATE.toISOString().split('T')[0],
    };
}

